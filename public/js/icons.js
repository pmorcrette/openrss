/** Replaces every `[data-icon]` placeholder inside `root` with its SVG. */
export function hydrateIcons(root = document) {
  for (const el of root.querySelectorAll('[data-icon]')) {
    el.replaceChildren(icon(el.dataset.icon));
  }
}
